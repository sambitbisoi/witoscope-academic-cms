// A fake Claude for local dev (npm run dev:files) and tests: no API calls, no cost.
// It reads the source question and settings from the prompt and returns drafts with the
// whole numbers shifted, so they pass the same checks a real draft must pass.
import type { AiClient } from '../../functions/_lib/ai.ts';
import type { RawDraft } from '../../shared/generation.ts';

const shift = (s: string, by: number) => s.replace(/\d+/g, (n) => String(Number(n) + by));

export function fakeDrafts(prompt: string): RawDraft[] {
  const count = Number(/Write (\d+) new draft/.exec(prompt)?.[1] ?? 1);
  const diffs = (/Math difficulty for the drafts, in order: ([^.]+)\./.exec(prompt)?.[1] ?? 'Medium').split(',').map((s) => s.trim()) as RawDraft['signature']['math_difficulty'][];
  const src = /Source question: (\{.*\})$/m.exec(prompt);
  const q = src ? JSON.parse(src[1]!) : { text: 'What is 2 + 3?', answer: { format: 'Typed-number', correct: '5', accepted: [], wrong_answers: [] }, concepts: [], signature: {}, solutions: { school: '2 + 3 = 5.' }, hints: ['Count on.'] };
  return Array.from({ length: count }, (_, i) => {
    const by = i + 1;
    const a = q.answer;
    return {
      text: shift(q.text, by), figure_description: '', format: a.format, options: (a.options ?? []).map((o: string) => shift(o, by)), correct: shift(a.correct, by),
      accepted: (a.accepted ?? []).map((o: string) => shift(o, by)),
      wrong_answers: (a.wrong_answers ?? []).map((w: { value: string; tag: string; misconception_id?: string; target_concept_id?: string; why?: string }) => ({
        value: shift(w.value, by), tag: w.tag, misconception_id: w.misconception_id ?? '', target_concept_id: w.target_concept_id ?? '', why: w.why ?? '' })),
      concepts: q.concepts ?? [],
      signature: { math_difficulty: diffs[i % diffs.length]!, is_pure_fact: false, reading: q.signature?.reading ?? 1, has_irrelevant_info: false, steps: q.signature?.steps ?? 1,
        working_memory: q.signature?.working_memory ?? 1, inhibition: q.signature?.inhibition ?? 0, visual: 0, strategy: 0, strategy_type: '', insight_id: '' },
      duration_s: 60, solution_school: shift(q.solutions?.school ?? 'Work it out.', by), solution_second: '', solution_second_type: 'none', solution_second_strategy: '',
      hints: (q.hints ?? ['Think it through.']).map((h: string) => shift(h, by)),
      tagging_why: [{ attribute: 'math_difficulty', why: 'Fake model (local dev): same skill, numbers changed.', confidence: 'medium' }],
      tagging_summary: 'Generated by the local fake model.',
    };
  });
}

const usage = { input_tokens: 1200, output_tokens: 900, cache_creation_input_tokens: 0, cache_read_input_tokens: 8000 };

export function fakeAiClient(): AiClient & { batches: Map<string, { custom_id: string; prompt: string }[]>; calls: Record<string, unknown>[] } {
  const batches = new Map<string, { custom_id: string; prompt: string }[]>();
  const calls: Record<string, unknown>[] = [];
  const promptOf = (p: Record<string, unknown>) => ((p.messages as { content: string }[])[0]!.content);
  return {
    batches, calls,
    async create(params) {
      calls.push(params);
      return { content: [{ type: 'text', text: JSON.stringify({ drafts: fakeDrafts(promptOf(params)) }) }], usage, model: String(params.model), stop_reason: 'end_turn' };
    },
    async batchCreate(requests) {
      const id = `msgbatch_fake${batches.size + 1}`;
      batches.set(id, requests.map((r) => ({ custom_id: r.custom_id, prompt: promptOf(r.params) })));
      calls.push(...requests.map((r) => r.params));
      return { id, processing_status: 'in_progress' };
    },
    async batchRetrieve(id) {
      const b = batches.get(id);
      return { id, processing_status: b ? 'ended' : 'canceling', request_counts: { processing: 0, succeeded: b?.length ?? 0, errored: 0, canceled: 0, expired: 0 } };
    },
    async *batchResults(id) {
      for (const r of batches.get(id) ?? []) {
        yield { custom_id: r.custom_id, result: { type: 'succeeded', message: { content: [{ type: 'text', text: JSON.stringify({ drafts: fakeDrafts(r.prompt) }) }], usage, model: 'claude-sonnet-5-5' } } };
      }
    },
  };
}
